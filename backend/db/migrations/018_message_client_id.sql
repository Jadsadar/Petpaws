-- =============================================================================
-- 018 — กันข้อความซ้ำตอนแอปส่งซ้ำ (idempotency key)
--
-- ตารางที่แตะ: messages (+client_id)
--
-- แอปสร้าง client_id (UUID) ให้ข้อความแต่ละข้อความเองตอนกดส่ง และใช้ค่าเดิมทุกครั้งที่ลองส่งซ้ำ
-- ถ้าคำขอแรกบันทึกสำเร็จแล้วแต่คำตอบหายระหว่างทาง (เน็ตหลุด/timeout) การกด "ลองใหม่"
-- จะได้ข้อความเดิมกลับไป ไม่เกิดข้อความซ้ำในห้อง — API เช็กก่อนบันทึก และ unique index
-- ด้านล่างกันกรณีคำขอซ้ำมาถึงพร้อมกันอีกชั้น
--
-- NULL = ข้อความจากแอปรุ่นก่อน / ข้อความระบบ ไม่ถูกบังคับ unique (partial index)
-- =============================================================================

BEGIN;

ALTER TABLE messages ADD COLUMN client_id uuid;

-- unique ต่อผู้ส่ง (ไม่ใช่ทั้งระบบ) — client_id มาจากแอป จึงไม่ไว้ใจให้ชนข้ามผู้ใช้กันได้
CREATE UNIQUE INDEX messages_sender_client_id_key
  ON messages (sender_id, client_id)
  WHERE client_id IS NOT NULL;

COMMIT;
